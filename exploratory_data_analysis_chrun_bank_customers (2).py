def plot_numeric_distributions(df, numeric_cols):
    """
    Generates a grid of histograms with Kernel Density Estimate (KDE) lines
    for numeric features to understand their shapes and spreads.
    """
    print("=" * 70)
    print("📈 GENERATING HISTOGRAMS FOR NUMERIC FEATURES")
    print("=" * 70)

    # Calculate optimal grid layout rows based on number of columns
    num_plots = len(numeric_cols)
    rows = (num_plots + 1) // 2  # Arrange in 2 columns

    fig, axes = plt.subplots(rows, 2, figsize=(14, rows * 4))
    axes = axes.flatten()  # Flatten the 2D grid matrix into a 1D array for easy looping

    for i, col in enumerate(numeric_cols):
        if col in df.columns:
            # kde=True adds a smooth probability density curve over the histogram bars
            sns.histplot(data=df, x=col, kde=True, ax=axes[i], color='skyblue', bins=30)
            axes[i].set_title(f'Distribution of {col}', fontsize=12, pad=10)
            axes[i].set_xlabel('')
            axes[i].set_ylabel('Count')
        else:
            axes[i].set_visible(False) # Hide extra empty subplots if columns don't match

    # Hide any unused subplots at the end of the grid
    for j in range(i + 1, len(axes)):
        axes[j].set_visible(False)

    plt.suptitle('Univariate Analysis: Numeric Distributions', fontsize=16, weight='bold', y=1.02)
    plt.tight_layout()
    plt.show()


def plot_categorical_distributions(df, categorical_cols):
    """
    Generates a grid of bar charts for categorical features to evaluate
    frequency counts and look for class imbalances.
    """
    print("\n" + "=" * 70)
    print("📊 GENERATING BAR CHARTS FOR CATEGORICAL FEATURES")
    print("=" * 70)

    num_plots = len(categorical_cols)
    rows = (num_plots + 1) // 2

    fig, axes = plt.subplots(rows, 2, figsize=(14, rows * 4))
    axes = axes.flatten()

    for i, col in enumerate(categorical_cols):
        if col in df.columns:
            # Generate value counts for text output reference
            print(f"\nValue Counts for {col}:")
            print(df[col].value_counts())

            # Create countplot (bar chart)
            sns.countplot(data=df, x=col, ax=axes[i], palette='Set2', order=df[col].value_counts().index)
            axes[i].set_title(f'Count of {col}', fontsize=12, pad=10)
            axes[i].set_xlabel('')
            axes[i].set_ylabel('Count')

            # Rotate labels if categories are long string names
            if df[col].nunique() > 3:
                axes[i].set_xticklabels(axes[i].get_xticklabels(), rotation=30, ha='right')
        else:
            axes[i].set_visible(False)

    for j in range(i + 1, len(axes)):
        axes[j].set_visible(False)

    plt.suptitle('Univariate Analysis: Categorical Value Counts', fontsize=16, weight='bold', y=1.02)
    plt.tight_layout()
    plt.show()

