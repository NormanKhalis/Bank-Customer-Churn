import pandas as pd

def generate_data_overview(file_path):
    """
    Loads an Excel file and prints its shape, column data types,
    null counts, null percentages, and complete summary statistics.
    """
    # Load the Excel file dynamically using the file_path variable
    try:
        df = pd.read_excel(file_path)
    except Exception as e:
        print(f"Error loading file: {e}")
        return None

    print("=" * 70)
    print(f"📊 DATA OVERVIEW FOR: {file_path}")
    print("=" * 70)

    # 1. Shape of the Dataset
    print(f"\n[1] DATASET SHAPE")
    print(f"• Total Rows (Observations): {df.shape[0]}")
    print(f"• Total Columns (Features): {df.shape[1]}")
    print("-" * 70)

    # 2. Column-level Metadata (Data Types & Missing Values)
    print(f"\n[2] COLUMN METADATA (DTYPES & NULLS)")
    metadata_df = pd.DataFrame({
        'Data Type': df.dtypes,
        'Null Count': df.isnull().sum(),
        'Null Percentage (%)': (df.isnull().sum() / len(df) * 100).round(2)
    })
    print(metadata_df)
    print("-" * 70)

    # 3. Complete Summary Statistics
    print(f"\n[3] SUMMARY STATISTICS (ALL COLUMNS)")
    summary_stats = df.describe(include='all')
    print(summary_stats)
    print("=" * 70)

    return df

