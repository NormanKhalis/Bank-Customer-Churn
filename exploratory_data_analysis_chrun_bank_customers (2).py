def segment_crosstab_dive(df):
    print("=" * 70)
    print("📋 CHURN RATES BY GEOGRAPHY AND GENDER")
    print("=" * 70)

    # Generates a matrix table of intersecting churn averages
    segmented_rates = pd.crosstab(
        index=df['Geography'],
        columns=df['Gender'],
        values=df['Exited'],
        aggfunc='mean'
    ) * 100  # Convert decimals to clean percentages

    print(segmented_rates.round(2).astype(str) + '%')
    print("=" * 70)


def plot_multi_variable_segments(df):
    print("\n🎨 GENERATING MULTI-VARIABLE FACET PLOT...")

    # This automatically instantiates a FacetGrid layout behind the scenes
    g = sns.catplot(
        data=df,
        x="Gender",
        y="Exited",
        hue="IsActiveMember",
        col="Geography",
        kind="bar",
        palette="muted",
        errorbar=None,
        height=4,
        aspect=0.8
    )

    # Formatting layout settings across all generated subplots
    g.set_ylabels("Churn Rate (Decimal %)")
    g.set_titles("{col_name} Market")

    plt.subplots_adjust(top=0.8)
    g.fig.suptitle('Segment Deep-Dive: Churn Rate by Gender, Activity, and Geography', fontsize=12, weight='bold')

    # This forces the windows to display the visual plots
    plt.show()

