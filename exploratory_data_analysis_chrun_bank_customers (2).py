def analyze_categorical_churn(df, cat_column, target_col='Exited'):
    print("\n" + "=" * 60)
    print(f"📊 CHURN RATE BY {cat_column.upper()}")
    print("=" * 60)

    churn_rates = df.groupby(cat_column)[target_col].agg(['count', 'mean']).rename(
        columns={'mean': 'Churn Rate', 'count': 'Total Customers'}
    )
    churn_rates['Churn Rate (%)'] = (churn_rates['Churn Rate'] * 100).round(2)
    print(churn_rates)

    plt.figure(figsize=(6, 4))
    ax = sns.barplot(x=cat_column, y=target_col, data=df, palette='Blues_d', errorbar=None)

    # Add labels to bars
    for p in ax.patches:
        ax.annotate(f'{p.get_height()*100:.1f}%',
                    (p.get_x() + p.get_width() / 2., p.get_height() + 0.01),
                    ha='center', va='center', weight='bold', fontsize=10)

    plt.title(f'Churn Rate by {cat_column}')
    plt.tight_layout()
    plt.show()


