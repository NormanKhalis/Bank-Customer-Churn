def plot_correlation_heatmap(df):
    """
    Isolates numeric columns, calculates Pearson correlation,
    and plots a clean Seaborn heatmap.
    """
    print("=" * 60)
    print("🔮 CALCULATING CORRELATION MATRIX")
    print("=" * 60)

    # 1. Filter out categorical columns (Heatmaps require numbers)
    numeric_df = df.select_dtypes(include=['int64', 'float64'])

    # 2. Compute the Pearson correlation matrix
    corr_matrix = numeric_df.corr()

    # Display raw numbers in console for precise reading
    print(corr_matrix.round(2))
    print("-" * 60)

    # 3. Setup the Matplotlib figure
    plt.figure(figsize=(10, 8))

    # 4. Generate Heatmap
    # 'annot=True' displays the values inside the squares
    # 'cmap' sets a diverging color scale (coolwarm perfectly highlights -1 vs +1)
    # 'fmt=".2f"' forces 2 decimal places
    # 'vmin' and 'vmax' anchor the colorbar limits firmly between -1 and 1
    sns.heatmap(
        corr_matrix,
        annot=True,
        cmap='coolwarm',
        fmt=".2f",
        linewidths=0.5,
        vmin=-1,
        vmax=1,
        square=True
    )

    plt.title('Correlation Matrix of Numeric Features', fontsize=14, pad=20)
    plt.xticks(rotation=45, ha='right') # Tilt X-axis labels to prevent overlapping
    plt.yticks(rotation=0)
    plt.tight_layout()

    # 5. Display the plot
    plt.show()

# Run the function
plot_correlation_heatmap(df)

