def check_target_imbalance(df, target_col='Exited'):
    """
    Plots the distribution of the target variable and prints class percentages
    to quickly check for class imbalance.
    """
    # 1. Calculate absolute counts and relative percentages
    counts = df[target_col].value_counts()
    percentages = df[target_col].value_counts(normalize=True) * 100

    print("=" * 50)
    print(f"📊 CLASS DISTRIBUTION FOR '{target_col}'")
    print("=" * 50)
    for idx in counts.index:
        print(f"Class {idx}: {counts[idx]} rows ({percentages[idx]:.2f}%)")
    print("=" * 50)

    # 2. Generate the Seaborn Countplot
    plt.figure(figsize=(6, 6))

    # Create the countplot
    ax = sns.countplot(x=target_col, data=df, palette='Set2')

    # Add percentage labels on top of the bars for quick scanning
    total = len(df)
    for p in ax.patches:
        percentage = f'{100 * p.get_height() / total:.1f}%'
        x_coord = p.get_x() + p.get_width() / 2 - 0.1
        y_coord = p.get_height() + (total * 0.01) # dynamic padding above bar
        ax.annotate(percentage, (x_coord, y_coord), fontsize=10, weight='bold')

    plt.title(f'Distribution of Target Variable ({target_col})', fontsize=12, pad=15)
    plt.xlabel('Customer Status (0 = Retained, 1 = Exited)', fontsize=10)
    plt.ylabel('Count', fontsize=10)
    plt.tight_layout()

    # Display the plot
    plt.show()

# Run the function
check_target_imbalance(df, target_col='Exited')

